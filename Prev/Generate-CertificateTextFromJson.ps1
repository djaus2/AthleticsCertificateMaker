# Generates a CertificateText.ps1 PowerShell file from a JSON representation.
param(
	[string]$JsonPath = "CertificateText.json",
	[string]$OutputPath = "CertificateText.ps1"
)

if (-not (Test-Path -LiteralPath $JsonPath)) {
	throw "JSON file not found: $JsonPath"
}

$raw = Get-Content -Raw -LiteralPath $JsonPath
$data = $raw | ConvertFrom-Json -Depth 10

function ToPsValue($v) {
	if ($null -eq $v) { return '$null' }
	switch ($v.GetType().Name) {
		'Boolean' {
			if ($v) { return '$true' }
			return '$false'
		}
		'Int32' { return $v.ToString() }
		'Int64' { return $v.ToString() }
		'Double' { return $v.ToString([System.Globalization.CultureInfo]::InvariantCulture) }
		default { return "'" + ($v -replace "'","''") + "'" }
	}
}

function ToPsHashtable([object]$obj, [int]$indent=0) {
	$pad = ' ' * $indent
	if ($obj -is [System.Collections.IEnumerable] -and -not ($obj -is [string])) {
		# array
		$items = @()
		foreach ($i in $obj) {
			if ($i -is [System.Management.Automation.PSCustomObject] -or $i -is [hashtable]) {
				$items += ToPsHashtable $i ($indent + 4)
			} else {
				$items += ToPsValue $i
			}
		}
		return "@(`n" + ($items -join ",`n") + "`n$pad)"
	}

	# object/hash
	$lines = @()
	$lines += "$pad@{"
	foreach ($k in $obj.PSObject.Properties.Name) {
		$val = $obj.$k
		if ($val -is [System.Management.Automation.PSCustomObject] -or $val -is [hashtable]) {
			$lines += "$( ' ' * ($indent + 4) )$k = $(ToPsHashtable $val ($indent + 4))"
		} elseif ($val -is [System.Collections.IEnumerable] -and -not ($val -is [string])) {
			# array
			$arrText = ToPsHashtable $val ($indent + 4)
			$lines += "$( ' ' * ($indent + 4) )$k = $arrText"
		} else {
			$lines += "$( ' ' * ($indent + 4) )$k = $(ToPsValue $val)"
		}
	}
	$lines += "$pad}"
	return ($lines -join "`n")
}

$out = @()
$out += "# Generated by Generate-CertificateTextFromJson.ps1 - do not edit by hand"
$out += "# Source: $JsonPath"
$out += ""

# Simple scalar assignments
$scalars = @(
	'CertificateTemplateFile','ParticipantCsvFile','ParticipantCsvDelimiter','SendUsingAccount',
	'DefaultTextColor','DefaultLabelColor','DefaultValueColor',
	'DefaultLabelTextSize','DefaultDataTextSize',
	'CertificateSmoothingMode','CertificateTextRenderingHint','ShowLocation','ShowHost'
)

foreach ($s in $scalars) {
	if ($data.PSObject.Properties.Name -contains $s) {
		$out += '$' + $s + ' = ' + (ToPsValue $data.$s)
	}
}

$out += ""
# Include helper functions for CSV delimiter detection / import (copied from original template)
$out += @'
function Get-ParticipantCsvDelimiter {
	param([string]$Path)

	switch ($ParticipantCsvDelimiter.ToLowerInvariant()) {
		"comma" { return ',' }
		"tab" { return "`t" }
		"auto" {
			$HeaderLine = Get-Content -LiteralPath $Path -TotalCount 1 -ErrorAction Stop
			if ([string]::IsNullOrWhiteSpace($HeaderLine)) {
				throw "Participant file is empty: $Path"
			}

			$CommaCount = ([regex]::Matches($HeaderLine, ',')).Count
			$TabCount = ([regex]::Matches($HeaderLine, "`t")).Count

			if ($CommaCount -eq $TabCount) {
				throw "Could not detect a comma or tab delimiter in the header of '$Path'."
			}
			if ($CommaCount -gt $TabCount) { return ',' }
			return "`t"
		}
		default {
			throw "Invalid ParticipantCsvDelimiter '$ParticipantCsvDelimiter'. Use Auto, Comma, or Tab."
		}
	}
}

function Import-ParticipantCsv {
	param([string]$Path)

	$Delimiter = Get-ParticipantCsvDelimiter -Path $Path
	Import-Csv -LiteralPath $Path -Delimiter $Delimiter
}
'@

$out += ""
# CertificateText
$out += "`$CertificateText = " + (ToPsHashtable $data.CertificateText 0)
$out += ""
# CertificateFields
$out += "`$CertificateFields = " + (ToPsHashtable $data.CertificateFields 0)

# Write file
[System.IO.File]::WriteAllLines($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputPath), $out)
Write-Output "Wrote $OutputPath"
